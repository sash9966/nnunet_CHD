"""Force low-res planner: always creates 3d_lowres + 3d_cascade_fullres configs.

The default ExperimentPlanner threshold of 0.25 only creates 3d_lowres when the
fullres patch covers <25% of the median image voxels. For cardiac CT, the fullres
patch typically covers 40-55% — above the threshold — so no lowres config is
generated by default.

Setting ``lowres_creation_threshold = 0.60`` forces low-res creation whenever the
fullres patch covers <60% of the median image, which in practice always triggers
for imageCHD cardiac CT volumes and gives:

    3d_lowres          — sees full cardiac anatomy per patch (global context)
    3d_cascade_fullres — refines boundaries using lowres prediction as prior

Usage (experiment planning step):
    nnUNetv2_plan_experiment -d <DATASET_ID> \\
        -pl ExperimentPlannerForceLowRes \\
        -c 3d_fullres

If you are using the ResEncUNet plans (nnUNetResEncUNetMPlans), inherit from the
matching ResEncUNet planner instead:

    from nnunetv2.experiment_planning.experiment_planners.residual_unets.residual_encoder_unet_planners import (
        nnUNetPlannerResEncM,
    )

    class ResEncMPlannerForceLowRes(nnUNetPlannerResEncM):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self.lowres_creation_threshold = 0.60
"""
from nnunetv2.experiment_planning.experiment_planners.default_experiment_planner import ExperimentPlanner


class ExperimentPlannerForceLowRes(ExperimentPlanner):
    """Forces 3d_lowres + 3d_cascade_fullres by raising the lowres threshold to 0.60.

    Inherits unchanged from ExperimentPlanner; only the threshold is changed.
    All spacing, patch-size, and batch-size logic remains identical to the default.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        # Default is 0.25.  Raising to 0.60 ensures lowres is created for cardiac CT
        # volumes where the fullres patch still covers a large fraction of the image.
        self.lowres_creation_threshold = 0.60
